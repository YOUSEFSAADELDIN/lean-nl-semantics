#!/usr/bin/env python3
"""Export the data layer for the Semantics Lab (viz/lab.html).

Three independent sources are joined, none re-derived by hand:

  1. viz/data/fracas_manifest.json (already generated by
     export_fracas_manifest.py) - the full 342-problem corpus with its
     English text, gold answer, and which problems have a real GF check
     or a hand-written Lean theorem. Reused as-is for "Explore FraCaS".

  2. viz/data/mono_nl_trace.json (already generated by
     export_mono_nl_trace.py from a real CI run) - the 65 theorems the
     deterministic monotonicity reasoner (`mono_nl`/`exist_nl`) actually
     closed on its own. Joined onto the manifest by problemId so the
     frontend can show "Lean verified" and "automatically solved by the
     reasoner" as two separate, sometimes-different facts, never
     implying the reasoner produced every historical theorem.

  3. A small, fixed "sentence builder" library: controlled-English
     sentences OUTSIDE the 342-problem corpus, built from a handful of
     restrictor/scope noun+adjective slots and four determiners. Every
     sentence's English text and GF abstract syntax tree are real - this
     script constructs the tree itself and calls the actual `gf` binary
     (FraCaSLogic.pgf, the same grammar the CI build compiles) to
     linearize it, exactly the technique gf/run_gf_tests.py already uses
     and documents (one shared `gf` session, split on the `FraCaSLogic> `
     prompt marker - a version that spawns one `gf` process per command
     was found to race on startup/piping and silently return blank
     output, see gf/run_gf_tests.py's own file-top comment).

     The reasoning step for each generated sentence pair is not run
     through Lean per instance. It cites one of eight already-Lean-
     verified GENERAL lemmas from LeanNLSemantics/FraCaS/Section1/GQ.lean
     (every_mono_scope, every_restrict, some_mono_scope, some_restrict,
     atLeast_mono_scope, atLeast_restrict, atMost_mono_scope,
     atMost_restrict), each of which is already a `forall`-quantified
     Lean theorem over ARBITRARY predicates - so any concrete
     instantiation (this generated sentence's restrictor/scope
     predicates) is automatically covered by the existing proof; nothing
     new needs to be checked per sentence. This is fundamentally
     different from "running Lean live" or an LLM guessing an answer,
     and the frontend must say so plainly (see LABEL text below).

     Direction of each lemma (whether ADDING or DROPPING a modifier is
     the licensed step) follows directly from each determiner's
     monotonicity profile, all read off GQ.lean's actual proven
     signatures:
       Every   - upward in scope (drop a scope modifier), downward in
                 restrictor (add a restrictor modifier)
       Some    - upward in both (drop a modifier either side)
       AtLeast - upward in both, same shape as Some
       AtMost  - downward in both (add a modifier either side)
     This is the classical monotonicity table (van Benthem; MacCartney &
     Manning's natural logic), not invented for this export.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GF_DIR = ROOT / "gf"
GF_LIB_PATH = "$HOME/gf-libs"
PATH_ARG = "-path=.:{lib}/alltenses:{lib}/prelude".format(lib=str(Path.home() / "gf-libs"))
PROMPT = "FraCaSLogic> "

LABEL_CACHED = "precomputed / kernel-verified"
LABEL_GENERAL = "general rule (Lean-verified for every predicate); this exact sentence pair was not itself compiled"

# ---------------------------------------------------------------------
# 1. Controlled vocabulary. Every noun/adjective here was confirmed
#    live against the real `gf` toolchain before being hardcoded (see
#    the shell probes this script's own commit message/PR description
#    refers to) - none of this is guessed.
# ---------------------------------------------------------------------

# (slot id, noun surface, noun GF fun, adjective surface, adjective GF fun)
CN_SLOTS = [
    dict(id="man", noun="man", noun_fun="man_N", adj="Italian", adj_fun="italian_A"),
    dict(id="tenor", noun="tenor", noun_fun="tenor_N", adj="great", adj_fun="great_A"),
    dict(id="person", noun="person", noun_fun="person_N", adj="dedicated", adj_fun="dedicated_A"),
    dict(id="student", noun="student", noun_fun="student_N", adj="Swedish", adj_fun="swedish_A"),
    dict(id="customer", noun="customer", noun_fun="customer_N", adj="noted", adj_fun="noted_A"),
]

_NUM_TREE = {
    2: "(pot0 n2)",
    3: "(pot0 n3)",
}


def _numeral_tree(n: int) -> str:
    return f"(NumCard (AdNum {{adn}} (NumNumeral (num (pot2as3 (pot1as2 (pot0as1 {_NUM_TREE[n]})))))))"


DETERMINERS = [
    dict(id="every", label="Every", family="Every", det_tree="every_Det"),
    dict(id="some", label="Some", family="Some", det_tree="somePl_Det"),
    dict(
        id="atleast3",
        label="At least 3",
        family="AtLeast",
        n=3,
        det_tree="(DetQuant IndefArt " + _numeral_tree(3).format(adn="at_least_AdN") + ")",
    ),
    dict(
        id="atmost2",
        label="At most 2",
        family="AtMost",
        n=2,
        det_tree="(DetQuant IndefArt " + _numeral_tree(2).format(adn="at_most_AdN") + ")",
    ),
]

# Lean lemma signatures, copied verbatim from GQ.lean (not paraphrased),
# for the frontend's Level 3 ("open the kernel") disclosure.
LEMMAS = {
    "every_mono_scope": "Every P Q → (∀ x, Q x → R x) → Every P R",
    "every_restrict": "Every R Q → Every P R → Every P Q",
    "some_mono_scope": "Some P Q → (∀ x, Q x → R x) → Some P R",
    "some_restrict": "Some P Q → Every P R → Some R Q",
    "atLeast_mono_scope": "AtLeast n P Q → (∀ x, Q x → R x) → AtLeast n P R",
    "atLeast_restrict": "AtLeast n P Q → Every P R → AtLeast n R Q",
    "atMost_mono_scope": "AtMost n P Q → (∀ x, R x → Q x) → AtMost n P R",
    "atMost_restrict": "AtMost n P Q → Every R P → AtMost n R Q",
}

# For each (determiner family, position), which toggle direction is the
# licensed entailment, and which lemma licenses it.
#   "broaden": premise = WITH the adjective (narrower), conclusion =
#              WITHOUT it (broader) - dropping a modifier.
#   "narrow":  premise = WITHOUT the adjective (broader), conclusion =
#              WITH it (narrower) - adding a modifier.
RULE_TABLE = {
    "Every": {
        "scope": dict(licensed="broaden", lemma="every_mono_scope"),
        "restrictor": dict(licensed="narrow", lemma="every_restrict"),
    },
    "Some": {
        "scope": dict(licensed="broaden", lemma="some_mono_scope"),
        "restrictor": dict(licensed="broaden", lemma="some_restrict"),
    },
    "AtLeast": {
        "scope": dict(licensed="broaden", lemma="atLeast_mono_scope"),
        "restrictor": dict(licensed="broaden", lemma="atLeast_restrict"),
    },
    "AtMost": {
        "scope": dict(licensed="narrow", lemma="atMost_mono_scope"),
        "restrictor": dict(licensed="narrow", lemma="atMost_restrict"),
    },
}


# ---------------------------------------------------------------------
# 2. Tiny GF tree builder. A tree is {"fun": str, "args": [tree, ...]},
#    matching gf/translate.py's own App(head, args) shape but kept as
#    plain dicts here since this script only ever builds trees forward
#    (English/Lean -> tree -> gf), never parses gf's tree notation back
#    (translate.py's own job, going the other direction).
# ---------------------------------------------------------------------


def leaf(fun: str) -> dict:
    return {"fun": fun, "args": []}


def app(fun: str, *args: dict) -> dict:
    return {"fun": fun, "args": list(args)}


def bare_cn(slot: dict) -> dict:
    return app("UseN", leaf(slot["noun_fun"]))


def mod_cn(slot: dict) -> dict:
    return app("AdjCN", app("PositA", leaf(slot["adj_fun"])), app("UseN", leaf(slot["noun_fun"])))


def cn_for(slot: dict, with_adj: bool) -> dict:
    return mod_cn(slot) if with_adj else bare_cn(slot)


def surface_for(slot: dict, with_adj: bool) -> str:
    return f"{slot['adj']} {slot['noun']}" if with_adj else slot["noun"]


def tree_to_gf_text(t: dict) -> str:
    if not t["args"]:
        return t["fun"]
    return t["fun"] + " " + " ".join(f"({tree_to_gf_text(a)})" for a in t["args"])


def det_tree_from_text(text: str) -> dict:
    """Only used for the four fixed determiner trees above - a tiny
    recursive-descent parser for GF's own s-expression notation (bare
    word, or `(Head arg1 arg2 ...)`), so DETERMINERS's det_tree strings
    become real tree dicts the same shape bare_cn/mod_cn produce,
    instead of living as opaque strings the frontend can't render."""
    tokens = []
    buf = ""
    for c in text:
        if c in "() ":
            if buf:
                tokens.append(buf)
                buf = ""
            if c in "()":
                tokens.append(c)
        else:
            buf += c
    if buf:
        tokens.append(buf)
    pos = 0

    def parse():
        nonlocal pos
        tok = tokens[pos]
        if tok == "(":
            pos += 1
            head = tokens[pos]
            pos += 1
            args = []
            while tokens[pos] != ")":
                args.append(parse())
            pos += 1
            return {"fun": head, "args": args}
        pos += 1
        return {"fun": tok, "args": []}

    return parse()


def sentence_tree(det: dict, restrictor_cn: dict, scope_cn: dict) -> dict:
    det_t = det_tree_from_text(det["det_tree"])
    subject = app("DetCN", det_t, restrictor_cn)
    predicate = app("UseComp", app("CompCN", scope_cn))
    return app("PredVP", subject, predicate)


def sentence_gf_command(det: dict, restrictor_cn: dict, scope_cn: dict) -> str:
    return "linearize " + tree_to_gf_text(sentence_tree(det, restrictor_cn, scope_cn))


def cn_gf_command(cn: dict) -> str:
    return "linearize " + tree_to_gf_text(cn)


def bare_licensing_command(slot: dict) -> str:
    """`every <adj> <noun> is a <noun>` - the raw conjunction-elimination
    fact each rule's "licensing implication" argument needs. Always
    true by construction (an intersective-adjective-modified CN entails
    its bare head noun); not a FraCaS problem, not a claim about the
    world."""
    return "linearize " + tree_to_gf_text(
        sentence_tree({"det_tree": "every_Det"}, mod_cn(slot), bare_cn(slot))
    )


# ---------------------------------------------------------------------
# 3. Build the full command batch, run it once through a real `gf`
#    session, and split results back onto each request - the same
#    reliable pattern gf/run_gf_tests.py uses (see its own file-top
#    comment for why a lone-process-per-command approach silently
#    returns blank output instead).
# ---------------------------------------------------------------------


def run_gf_batch(commands: list[str]) -> list[str]:
    pgf = GF_DIR / "FraCaSLogic.pgf"
    if not pgf.exists():
        print(f"error: {pgf} not found - run `gf -make` first", file=sys.stderr)
        sys.exit(1)
    script = "\n".join(commands) + "\nquit\n"
    result = subprocess.run(
        ["gf", "-path=.:" + str(Path.home() / "gf-libs" / "alltenses") + ":" + str(Path.home() / "gf-libs" / "prelude"), str(pgf)],
        input=script,
        capture_output=True,
        text=True,
        cwd=GF_DIR,
        timeout=120,
    )
    if result.returncode != 0 and not result.stdout:
        print(result.stderr, file=sys.stderr)
        sys.exit(1)
    segments = result.stdout.split(PROMPT)
    if len(segments) < len(commands) + 1:
        print(
            f"error: expected {len(commands) + 1} '{PROMPT}'-delimited segments, "
            f"got {len(segments)}",
            file=sys.stderr,
        )
        print(result.stdout[-2000:], file=sys.stderr)
        sys.exit(1)
    out = []
    for seg in segments[1 : len(commands) + 1]:
        stripped = seg.strip()
        out.append(stripped.splitlines()[0].strip() if stripped else "")
    return out


def build_library() -> dict:
    commands: list[str] = []
    index: list[tuple] = []  # (kind, payload) matching commands 1:1

    # 3a. Licensing facts, one per CN slot.
    for slot in CN_SLOTS:
        commands.append(bare_licensing_command(slot))
        index.append(("license", slot["id"]))

    # 3b. Full sentence library: every (det, restrictorSlot, rToggle,
    #     scopeSlot, sToggle) combination - 4 x 5 x 2 x 5 x 2 = 400 real
    #     sentences, each independently linearized.
    combos = []
    for det in DETERMINERS:
        for r_slot in CN_SLOTS:
            for r_adj in (False, True):
                for s_slot in CN_SLOTS:
                    if s_slot["id"] == r_slot["id"]:
                        # Same noun on both sides collapses into either
                        # a self-restatement ("every man is a man") or
                        # the bare licensing fact itself ("every great
                        # tenor is a tenor") - not an interesting
                        # reasoning instance, so restrictor and scope
                        # always draw from different slots.
                        continue
                    for s_adj in (False, True):
                        combos.append((det, r_slot, r_adj, s_slot, s_adj))
    for det, r_slot, r_adj, s_slot, s_adj in combos:
        r_cn = cn_for(r_slot, r_adj)
        s_cn = cn_for(s_slot, s_adj)
        commands.append(sentence_gf_command(det, r_cn, s_cn))
        index.append(("sentence", (det, r_slot, r_adj, s_slot, s_adj)))

    print(f"running {len(commands)} real `gf` linearize calls in one batch session...", file=sys.stderr)
    results = run_gf_batch(commands)

    licensing_by_slot = {}
    sentences = {}
    for (kind, payload), text in zip(index, results):
        if kind == "license":
            licensing_by_slot[payload] = text
        else:
            det, r_slot, r_adj, s_slot, s_adj = payload
            key = (det["id"], r_slot["id"], r_adj, s_slot["id"], s_adj)
            sentences[key] = text

    def sentence_record(det, r_slot, r_adj, s_slot, s_adj):
        key = (det["id"], r_slot["id"], r_adj, s_slot["id"], s_adj)
        english = sentences[key]
        r_cn = cn_for(r_slot, r_adj)
        s_cn = cn_for(s_slot, s_adj)
        tree = sentence_tree(det, r_cn, s_cn)
        return {
            "determinerId": det["id"],
            "restrictor": {"slot": r_slot["id"], "withAdjective": r_adj, "surface": surface_for(r_slot, r_adj)},
            "scope": {"slot": s_slot["id"], "withAdjective": s_adj, "surface": surface_for(s_slot, s_adj)},
            "english": english,
            "tree": tree,
            "gfText": tree_to_gf_text(tree),
        }

    # 3c. Assemble "moves": for every base combination, the two legal
    #     single-toggle transitions (flip restrictor adjective, flip
    #     scope adjective), each carrying its own verdict + lemma.
    moves = []
    for det in DETERMINERS:
        family = det["family"]
        for r_slot in CN_SLOTS:
            for r_adj in (False, True):
                for s_slot in CN_SLOTS:
                    if s_slot["id"] == r_slot["id"]:
                        continue
                    for s_adj in (False, True):
                        base = sentence_record(det, r_slot, r_adj, s_slot, s_adj)
                        for position, flip_key in (("scope", "scope"), ("restrictor", "restrictor")):
                            if position == "scope":
                                other = sentence_record(det, r_slot, r_adj, s_slot, not s_adj)
                                toggled_on = s_adj is False  # transitioning bare -> adj (adding)
                            else:
                                other = sentence_record(det, r_slot, not r_adj, s_slot, s_adj)
                                toggled_on = r_adj is False
                            direction = "narrow" if toggled_on else "broaden"
                            rule = RULE_TABLE[family][position]
                            licensed = rule["licensed"] == direction
                            lemma = rule["lemma"]
                            # `base` is always the sentence before the
                            # click, `other` the sentence after it -
                            # `direction` alone (narrow-going vs.
                            # broaden-going) already says whether this
                            # specific click matches the family's
                            # licensed direction, so premise/conclusion
                            # never need reordering.
                            premise, conclusion = base, other
                            slot_for_fact = s_slot["id"] if position == "scope" else r_slot["id"]
                            moves.append({
                                "determinerId": det["id"],
                                "determinerLabel": det["label"],
                                "family": family,
                                "position": position,
                                "direction": direction,
                                "premise": premise,
                                "conclusion": conclusion,
                                "licensed": licensed,
                                "lemma": lemma if licensed else None,
                                "lemmaSignature": LEMMAS[lemma] if licensed else None,
                                "licensingFact": licensing_by_slot[slot_for_fact] if licensed else None,
                                "label": LABEL_GENERAL,
                            })

    return {
        "cnSlots": CN_SLOTS,
        "determiners": [{"id": d["id"], "label": d["label"], "family": d["family"]} for d in DETERMINERS],
        "lemmas": LEMMAS,
        "moves": moves,
    }


# ---------------------------------------------------------------------
# 4. Join the FraCaS corpus manifest with the reasoner trace.
# ---------------------------------------------------------------------


def build_fracas_index() -> dict:
    manifest = json.loads((ROOT / "viz" / "data" / "fracas_manifest.json").read_text())
    trace = json.loads((ROOT / "viz" / "data" / "mono_nl_trace.json").read_text())

    reasoner_by_pid: dict[int, dict] = {}
    for th in trace["theorems"]:
        pid = th.get("problemId")
        if pid is None:
            continue
        rec = reasoner_by_pid.setdefault(pid, {"tactics": set(), "rules": set()})
        rec["tactics"].add(th["tactic"])
        rec["rules"].add(th.get("rule") or "")

    for rec in manifest["problems"]:
        pid = rec["id"]
        solved = reasoner_by_pid.get(pid)
        rec["reasonerSolved"] = solved is not None
        rec["reasonerTactics"] = sorted(solved["tactics"]) if solved else []
        rec["reasonerRules"] = sorted(r for r in solved["rules"] if r) if solved else []

    return {
        "sections": manifest["sections"],
        "totalProblems": manifest["totalProblems"],
        "problems": manifest["problems"],
        "reasonerSummary": trace["summary"],
    }


def build_trace_library() -> list[dict]:
    trace = json.loads((ROOT / "viz" / "data" / "mono_nl_trace.json").read_text())
    return trace["theorems"]


def main() -> None:
    data = {
        "generatedFrom": {
            "fracasManifest": "viz/data/fracas_manifest.json",
            "monoNlTrace": "viz/data/mono_nl_trace.json",
            "gfGrammar": "gf/FraCaSLogic.pgf (real `gf` linearize calls, run by this script)",
        },
        "fracas": build_fracas_index(),
        "traceLibrary": build_trace_library(),
        "builder": build_library(),
    }
    out_path = ROOT / "viz" / "data" / "lab.json"
    out_path.write_text(json.dumps(data, separators=(",", ":")))
    n_moves = len(data["builder"]["moves"])
    n_licensed = sum(1 for m in data["builder"]["moves"] if m["licensed"])
    print(
        f"wrote {out_path}: {data['fracas']['totalProblems']} FraCaS problems, "
        f"{len(data['traceLibrary'])} trace entries, {n_moves} builder moves "
        f"({n_licensed} licensed, {n_moves - n_licensed} not decided)",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
