#!/usr/bin/env python3
"""Write gf/default_translations.tsv: `translate.py`'s DEFAULT-mode
translation of every confirmed hand-built tree in `run_gf_tests.py`.

`translate.py` serves two parts of this project: its default mode feeds
the GF cross-check of the hand-written FraCaS corpus
(`scripts/gen_gf_cross_check.py`), and its reading modes feed the
end-to-end pipeline (`EndToEnd/gen_claims.py`). The reading modes live
behind one gate (`_READING != "default"`), but nothing structural stops a
change made for the end-to-end pipeline from also changing the default
mode. This snapshot makes any such change visible: CI regenerates it and
fails if it differs from the committed copy, so a default-mode change is
always a deliberate, reviewed edit to this file, never a side effect.

Needs no gf binary. Re-run after an intended default-mode change and
commit the result; do not hand-edit the output.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

GF_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(GF_DIR))
from translate import parse_tree, translate_cl  # noqa: E402


def to_clause(t):
    if t.head == "UttS" and len(t.args) == 1:
        t = t.args[0]
    if t.head == "UseCl" and len(t.args) == 3 and t.args[1].head == "PPos":
        return t.args[2]
    return t


def main() -> None:
    spec = importlib.util.spec_from_file_location("run_gf_tests", GF_DIR / "run_gf_tests.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    rows = []
    translated = 0
    for label, cmd, _english in mod.CHECKS:
        if not cmd.startswith("linearize "):
            continue
        tree = cmd[len("linearize "):]
        while tree.startswith("-"):  # linearize flags, e.g. -lang=...
            tree = tree.split(" ", 1)[1]
        try:
            prop = translate_cl(to_clause(parse_tree(tree))).lean_prop
            translated += 1
        except Exception:
            prop = "-"  # outside translate.py's default coverage
        rows.append(f"{label}\t{prop}")
    (GF_DIR / "default_translations.tsv").write_text(
        "# Generated by gf/snapshot_default_translations.py - do not hand-edit.\n"
        "# label<TAB>default-mode translation ('-' = not translated)\n"
        + "\n".join(rows) + "\n"
    )
    print(f"{len(rows)} trees, {translated} translated")


if __name__ == "__main__":
    main()
