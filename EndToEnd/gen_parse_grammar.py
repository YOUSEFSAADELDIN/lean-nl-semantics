#!/usr/bin/env python3
"""Generate EndToEnd/FraCaSParse.gf / EndToEnd/FraCaSParseEng.gf: a
*restricted* view of gf/FraCaSLogic for `parse`, inheriting only the
functions the CI-confirmed trees in `gf/run_gf_tests.py`'s `CHECKS` actually use.

Why: `parse` against the full FraCaSLogic grammar (all of the RGL's
Noun/Verb/Sentence/... modules plus DictEng's ~65k words) is unusable for
FraCaS input - measured on "every Italian man wants to be a great tenor":
69,115 readings after 5 minutes with no end in sight, none of the first
tens of thousands free of junk constructions (`ProDrop ?18`, `ApposCN`,
`GenNP`). See gf/NOTES.md. GF's restricted inheritance (`M [f, g, ...]`)
keeps exactly the listed functions and nothing else, which brings the same
sentence down to 4 readings in well under a second.

What this restriction is, stated honestly: the function/word list is read
off the hand-built trees, so this is a *controlled-language grammar fit to
FraCaS's own vocabulary and constructions* (the same kind of artifact
FraCoq's own FraCaS-specific GF grammar is) - not open-domain parsing.
What it does NOT encode is which tree goes with which sentence: `parse`
still has to find the structure on its own, and returns every reading the
restricted grammar licenses (median 3, max in the hundreds), ranked
generically by `parse_rank.py`.

Re-run after `gf/run_gf_tests.py` changes; do not hand-edit the output.
"""
from __future__ import annotations

import importlib.util
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
GF_DIR = HERE.parent / "gf"

# Categories that live outside `Cat` (Conjunction's list categories, the
# numeral sub-categories) - restricted inheritance needs them named, or
# linking fails with e.g. "missing category ListCN".
EXTRA_CATS = [
    "ListCN", "ListNP", "ListS", "ListAP", "ListAdv", "ListRS",
    "Digit", "Sub10", "Sub100", "Sub1000", "Sub1000000",
    "Sub1000000000", "Sub1000000000000",
    "EllAux",  # FraCaSLogic.gf's own, for VP ellipsis
]


def confirmed_functions() -> list[str]:
    spec = importlib.util.spec_from_file_location("run_gf_tests", GF_DIR / "run_gf_tests.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    names: set[str] = set()
    for check in mod.CHECKS:
        cmd = check[1]
        if not cmd.startswith("linearize "):
            continue
        tree = cmd[len("linearize "):]
        while tree.startswith("-"):  # linearize flags, e.g. -lang=...
            tree = tree.split(" ", 1)[1]
        names |= set(re.findall(r"[A-Za-z_][A-Za-z0-9_']*", tree))
    return sorted(names)


def main() -> None:
    fns = EXTRA_CATS + confirmed_functions()
    listing = ",\n  ".join(", ".join(fns[i:i + 8]) for i in range(0, len(fns), 8))
    header = "-- Generated by EndToEnd/gen_parse_grammar.py - do not hand-edit; re-run it.\n"
    (HERE / "FraCaSParse.gf").write_text(
        header
        + "abstract FraCaSParse = Cat, FraCaSLogic [\n  " + listing + "\n] ** {\n"
        + "  flags startcat = Cl ;\n}\n"
    )
    (HERE / "FraCaSParseEng.gf").write_text(
        header
        + "concrete FraCaSParseEng of FraCaSParse = CatEng, FraCaSLogicEng [\n  " + listing
        + "\n] ** {\n}\n"
    )
    print(f"{len(fns)} categories/functions inherited")


if __name__ == "__main__":
    main()
