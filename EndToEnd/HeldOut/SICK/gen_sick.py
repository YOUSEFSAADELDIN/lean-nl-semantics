#!/usr/bin/env python3
"""The second held-out test: SICK's test split through the pipeline as it
stood at commit ac92c4e, frozen - see README.md here.

The procedure is MED's (`../gen_heldout.py`), unchanged: the frozen
pipeline (`gen_claims.assemble`, the name check included), with the parse
grammar's vocabulary extended by one fixed rule and nothing else
(`gen_heldout.lexicon`: every open-class DictEng entry of a word the
FraCaS grammar does not know; a capitalized word with no entry is a proper
noun). Sentence A is the premise and sentence B the hypothesis; the gold
label is SICK's `entailment_label`.

Run from the repository root (needs the `gf` binary and the compiled
`EndToEnd/FraCaSEndToEnd.pgf`). Writes SickNames*.gf, SickParse*.gf,
Claims.lean and sick.json. Do not hand-edit the output, and do not change
the pipeline in response to what this test shows.
"""
from __future__ import annotations

import collections
import csv
import functools
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import gen_heldout  # noqa: E402
from gen_heldout import gen_claims, gen_parse_grammar, parse_rank  # noqa: E402

DATA = HERE / "SICK_test.tsv"
PGF = HERE / "SickParse.pgf"
OUT = HERE / "Claims.lean"
STATS = HERE / "sick.json"
PARSE_TIMEOUT = gen_heldout.PARSE_TIMEOUT
LABELS = {"ENTAILMENT": "E", "CONTRADICTION": "C", "NEUTRAL": "N"}


def load():
    with DATA.open(encoding="utf-8") as f:
        return [
            {"pairID": r["pair_ID"], "sentence1": r["sentence_A"], "sentence2": r["sentence_B"],
             "gold": LABELS[r["entailment_label"]]}
            for r in csv.DictReader(f, delimiter="\t")
        ]


def write_grammar(functions, names) -> None:
    head = "-- Generated by EndToEnd/HeldOut/SICK/gen_sick.py - do not hand-edit; re-run it.\n"
    base = gen_parse_grammar.EXTRA_CATS + gen_parse_grammar.confirmed_functions()
    fns = sorted(set(base) | set(functions))
    listing = ",\n  ".join(", ".join(fns[i:i + 8]) for i in range(0, len(fns), 8))
    (HERE / "SickNames.gf").write_text(
        head + "abstract SickNames = Cat ** {\n  fun\n"
        + "".join(f"    {f} : PN ;\n" for f in sorted(names)) + "}\n")
    (HERE / "SickNamesEng.gf").write_text(
        head + "concrete SickNamesEng of SickNames = CatEng ** open ParadigmsEng in {\n  lin\n"
        + "".join(f'    {f} = mkPN "{names[f]}" ;\n' for f in sorted(names)) + "}\n")
    (HERE / "SickParse.gf").write_text(
        head + "abstract SickParse = Cat, SickNames, FraCaSEndToEnd [\n  " + listing
        + "\n] ** {\n  flags startcat = Cl ;\n}\n")
    (HERE / "SickParseEng.gf").write_text(
        head + "concrete SickParseEng of SickParse = CatEng, SickNamesEng, FraCaSEndToEndEng [\n  "
        + listing + "\n] ** {\n}\n")


def compile_grammar() -> None:
    libs = os.path.expanduser("~/gf-libs")
    subprocess.run(
        ["gf", "-make", f"-path=.:../..:../../../gf:{libs}/alltenses:{libs}/prelude", "SickParseEng.gf"],
        cwd=HERE, check=True, capture_output=True,
    )


def _parse(sentence, pgf=None, timeout=None, require_well_formed=False):
    try:
        return parse_rank.parse_readings(sentence, pgf=PGF, timeout=PARSE_TIMEOUT,
                                         require_well_formed=require_well_formed)
    except subprocess.TimeoutExpired:
        return None, []


def main() -> None:
    rows = load()
    stats: dict = {"source": len(rows), "stages": collections.Counter()}
    functions, names = gen_heldout.lexicon(rows)
    write_grammar(functions, names)
    compile_grammar()
    stats["added_functions"], stats["added_names"] = len(functions), len(names)

    # The pipeline, unchanged, against this test's grammar.
    gen_claims.tokenize = functools.partial(parse_rank.tokenize, pgf=PGF)
    gen_claims.parse_readings = _parse
    vocab = parse_rank.vocabulary(PGF)

    emitted, per_problem = [], {}
    for r in rows:
        pid = int(r["pairID"])
        sentences = [("premise 1", r["sentence1"]), ("hypothesis", r["sentence2"])]
        if any(t not in vocab for _role, s in sentences for t in gen_claims.tokenize(s).split()):
            stage = "a word outside the grammar's closed classes"
        else:
            claims, reason = gen_claims.assemble(pid, sentences)
            if claims is None:
                stage = "does not parse" if "does not parse" in reason else "does not translate"
            else:
                stage = "reached"
                emitted.append((pid, r["gold"], claims))
        stats["stages"][stage] += 1
        per_problem[pid] = stage
    write_claims(emitted)
    stats["stages"] = dict(stats["stages"])
    stats["reached_by_gold"] = dict(collections.Counter(g for _p, g, _c in emitted))
    STATS.write_text(json.dumps({**stats, "problems": per_problem}, indent=1, sort_keys=True) + "\n")
    print(json.dumps(stats, indent=1))


def write_claims(emitted) -> None:
    lines = [
        "-- Generated by EndToEnd/HeldOut/SICK/gen_sick.py - do not hand-edit; re-run it.",
        "-- Derived from SICK (Marelli et al. 2014), CC BY-NC-SA 3.0: see CREDITS.md.",
        "import LeanNLSemantics.FraCaS.Types",
        "import LeanNLSemantics.FraCaS.Section1.GQ",
        "import LeanNLSemantics.FraCaS.Section2.Plurals",
        "import EndToEnd.Quantifiers",
        "",
        "/-!",
        "# The second held-out test: SICK's test split through the frozen pipeline",
        "",
        "Each `sick_N_*` is SICK pair N (sentence A the premise, B the",
        "hypothesis), translated by the end-to-end pipeline exactly as it",
        "translates FraCaS (`gen_claims.assemble`), with the parse grammar's",
        "vocabulary extended by dictionary words only. See",
        "`EndToEnd/HeldOut/SICK/README.md`. Scored by `EndToEnd/SickScan.lean`.",
        "-/",
        "",
        "namespace FraCaS.HeldOut.SICK",
        "namespace Claims",
        "open FraCaS.Section1 FraCaS.Section2 FraCaS.EndToEnd",
        "",
    ]
    for pid, _gold, c in emitted:
        for i, asg in enumerate(c["assignments"]):
            for kind in ("yes", "no", "bk_yes", "bk_no"):
                lines.append(f"def sick_{pid}_{kind}_{i} : Prop :=\n  {asg[kind]}\n")
    lines += ["end Claims", ""]

    def names(pid, c, kind):
        return ", ".join(f"``Claims.sick_{pid}_{kind}_{i}" for i in range(len(c["assignments"])))

    for reg, prefix in (("registry", ""), ("registryBk", "bk_")):
        lines.append("set_option maxRecDepth 100000 in")
        lines.append('/-- `(SICK pair_ID, gold "E"/"C"/"N", yes-claims, no-claims)`. -/')
        lines.append(f"def {reg} : List (Nat × String × List Lean.Name × List Lean.Name) := [")
        lines.append(",\n".join(
            f'  ({pid}, "{gold}", [{names(pid, c, prefix + "yes")}], [{names(pid, c, prefix + "no")}])'
            for pid, gold, c in emitted))
        lines += ["]", ""]
    lines += ["end FraCaS.HeldOut.SICK", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
