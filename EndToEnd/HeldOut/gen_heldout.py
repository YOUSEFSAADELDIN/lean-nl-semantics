#!/usr/bin/env python3
"""The held-out test: the end-to-end pipeline, frozen, on problems it was
never developed on - MED (Yanaka et al. 2019), see README.md here.

Everything that decides an answer is the pipeline's own, unchanged:
the constructions the parse grammar admits (`gen_parse_grammar.py`'s
list, read off the FraCaS checks), the ranker, discourse resolution,
the readings and the every-reading rule (`readings.py`), the translator,
the background knowledge (`background.py`), the assembly
(`gen_claims.assemble`) and the prover. The one thing added is
vocabulary, by a fixed rule and nothing else:

- a token the FraCaS parse grammar does not know gets every open-class
  entry (noun, verb, adjective, adverb, proper noun; never determiners,
  pronouns, prepositions or conjunctions) that the RGL's general English
  dictionary (DictEng, already part of `FraCaSEndToEnd`) gives it;
- a capitalized token with no such entry is a proper noun.

So a problem is reached only if its English uses constructions the
pipeline already had for FraCaS. Problems are excluded beforehand if MED
marks them as taken from FraCaS, or if either sentence is a FraCaS
sentence verbatim.

Stages (run from the repository root; needs the `gf` binary and the
compiled `EndToEnd/FraCaSEndToEnd.pgf`, like gen_claims.py):
1. writes HeldOutParse.gf/Eng.gf and HeldOutNames.gf/Eng.gf, and
   compiles HeldOutParse.pgf (not committed);
2. parses, resolves and translates each remaining problem with
   `gen_claims.assemble`, and writes Claims.lean and heldout.json.

Do not hand-edit the output. Do not change the pipeline in response to
what this test shows; see README.md.
"""
from __future__ import annotations

import collections
import csv
import functools
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
END_TO_END = HERE.parent
ROOT = END_TO_END.parent
sys.path.insert(0, str(END_TO_END))
sys.path.insert(0, str(ROOT / "gf"))

import gen_claims  # noqa: E402
import gen_parse_grammar  # noqa: E402
import parse_rank  # noqa: E402

MED = HERE / "MED.tsv"
FULL_PGF = END_TO_END / "FraCaSEndToEnd.pgf"
HELD_PGF = HERE / "HeldOutParse.pgf"
OUT = HERE / "Claims.lean"
STATS = HERE / "heldout.json"
PARSE_TIMEOUT = 60  # seconds per parse call; a timeout counts as no parse

OPEN_CLASS = ("_N", "_N2", "_N3", "_A", "_A2", "_V", "_V2", "_V3", "_VV", "_VS", "_VQ",
              "_VA", "_V2V", "_V2S", "_V2Q", "_V2A", "_Adv", "_AdV", "_AdA", "_PN")


def load_med():
    with MED.open() as f:
        return list(csv.DictReader(f, delimiter="\t"))


def fracas_sentences() -> set:
    norm = lambda s: re.sub(r"\s+", " ", s.strip().rstrip(".?!").lower())  # noqa: E731
    out = set()
    for _i, premises, hypothesis, _a in gen_claims.load_problems():
        out |= {norm(s) for s in [*premises, hypothesis]}
    return out, norm


def analyse(words: list[str]) -> dict:
    """word -> the dictionary functions it is a form of (`gf`'s `ma`)."""
    out = subprocess.run(
        ["gf", "--run", str(FULL_PGF)],
        input='ma "' + " ".join(words) + '"\n', capture_output=True, text=True,
    ).stdout
    analyses: dict = {}
    cur = None
    for line in out.split("\n"):
        if not line.strip():
            cur = None
        elif " : " not in line:
            cur = line.strip()
            analyses[cur] = set()
        elif cur is not None:
            analyses[cur].add(line.split(" : ")[0].strip())
    return analyses


def lexicon(problems):
    """The open-class dictionary functions and the proper nouns the
    problems' unknown tokens need."""
    known = parse_rank.vocabulary()
    unknown = sorted({
        t for r in problems for s in (r["sentence1"], r["sentence2"])
        for t in parse_rank.tokenize(s).split() if t not in known
    })
    plain = [w for w in unknown if re.fullmatch(r"[A-Za-z][A-Za-z'\-]*", w)]
    analyses = analyse(sorted({*plain, *(w.lower() for w in plain)}))
    functions, names = set(), {}
    for w in plain:
        fs = {f for f in analyses.get(w, set()) | analyses.get(w.lower(), set()) if f.endswith(OPEN_CLASS)}
        if fs:
            functions |= fs
        elif w[:1].isupper() and w[1:].islower() and w.isalpha():
            names[w.lower() + "_PN"] = w
    return sorted(functions), names


def write_grammar(functions, names) -> None:
    head = "-- Generated by EndToEnd/HeldOut/gen_heldout.py - do not hand-edit; re-run it.\n"
    base = gen_parse_grammar.EXTRA_CATS + gen_parse_grammar.confirmed_functions()
    fns = sorted(set(base) | set(functions))
    listing = ",\n  ".join(", ".join(fns[i:i + 8]) for i in range(0, len(fns), 8))
    (HERE / "HeldOutNames.gf").write_text(
        head + "abstract HeldOutNames = Cat ** {\n  fun\n"
        + "".join(f"    {f} : PN ;\n" for f in sorted(names)) + "}\n")
    (HERE / "HeldOutNamesEng.gf").write_text(
        head + "concrete HeldOutNamesEng of HeldOutNames = CatEng ** open ParadigmsEng in {\n  lin\n"
        + "".join(f'    {f} = mkPN "{names[f]}" ;\n' for f in sorted(names)) + "}\n")
    (HERE / "HeldOutParse.gf").write_text(
        head + "abstract HeldOutParse = Cat, HeldOutNames, FraCaSEndToEnd [\n  " + listing
        + "\n] ** {\n  flags startcat = Cl ;\n}\n")
    (HERE / "HeldOutParseEng.gf").write_text(
        head + "concrete HeldOutParseEng of HeldOutParse = CatEng, HeldOutNamesEng, FraCaSEndToEndEng [\n  "
        + listing + "\n] ** {\n}\n")


def compile_grammar() -> None:
    libs = os.path.expanduser("~/gf-libs")
    subprocess.run(
        ["gf", "-make", f"-path=.:..:../../gf:{libs}/alltenses:{libs}/prelude", "HeldOutParseEng.gf"],
        cwd=HERE, check=True, capture_output=True,
    )


def _parse(sentence, pgf=None, timeout=None, require_well_formed=False):
    try:
        return parse_rank.parse_readings(sentence, pgf=HELD_PGF, timeout=PARSE_TIMEOUT,
                                         require_well_formed=require_well_formed)
    except subprocess.TimeoutExpired:
        return None, []


def main() -> None:
    rows = load_med()
    seen, norm = fracas_sentences()
    stats: dict = {"source": len(rows), "excluded_fracas": 0, "stages": collections.Counter()}
    candidates = []
    for r in rows:
        if "FraCaS" in r["genre"] or norm(r["sentence1"]) in seen or norm(r["sentence2"]) in seen:
            stats["excluded_fracas"] += 1
        else:
            candidates.append(r)
    functions, names = lexicon(candidates)
    write_grammar(functions, names)
    compile_grammar()
    stats["added_functions"], stats["added_names"] = len(functions), len(names)

    # The pipeline, unchanged, against the held-out grammar.
    gen_claims.tokenize = functools.partial(parse_rank.tokenize, pgf=HELD_PGF)
    gen_claims.parse_readings = _parse
    vocab = parse_rank.vocabulary(HELD_PGF)

    emitted, per_problem = [], {}
    for r in candidates:
        pid = int(r["pairID"])
        sentences = [("premise 1", r["sentence1"]), ("hypothesis", r["sentence2"])]
        if any(t not in vocab for _role, s in sentences for t in gen_claims.tokenize(s).split()):
            stage = "a word outside the grammar's closed classes"
        else:
            claims, reason = gen_claims.assemble(pid, sentences)
            if claims is None:
                stage = "does not parse" if "does not parse" in reason else "does not translate"
            else:
                stage = "reached"
                emitted.append((pid, r["gold_label"], claims))
        stats["stages"][stage] += 1
        per_problem[pid] = stage
    write_claims(emitted)
    stats["stages"] = dict(stats["stages"])
    stats["reached_by_gold"] = dict(collections.Counter(g for _p, g, _c in emitted))
    STATS.write_text(json.dumps({**stats, "problems": per_problem}, indent=1, sort_keys=True) + "\n")
    print(json.dumps(stats, indent=1))


def write_claims(emitted) -> None:
    lines = [
        "-- Generated by EndToEnd/HeldOut/gen_heldout.py - do not hand-edit; re-run it.",
        "import LeanNLSemantics.FraCaS.Types",
        "import LeanNLSemantics.FraCaS.Section1.GQ",
        "import LeanNLSemantics.FraCaS.Section2.Plurals",
        "import EndToEnd.Quantifiers",
        "",
        "/-!",
        "# The held-out test: MED problems through the frozen pipeline",
        "",
        "Each `med_N_*` is MED problem N (pairID), translated by the end-to-end",
        "pipeline exactly as it translates FraCaS (`gen_claims.assemble`), with",
        "the parse grammar's vocabulary extended by dictionary words only. See",
        "`EndToEnd/HeldOut/README.md`. Scored by `EndToEnd/HeldOutScan.lean`.",
        "-/",
        "",
        "namespace FraCaS.HeldOut",
        "namespace Claims",
        "open FraCaS.Section1 FraCaS.Section2 FraCaS.EndToEnd",
        "",
    ]
    for pid, _gold, c in emitted:
        for i, asg in enumerate(c["assignments"]):
            for kind in ("yes", "no", "bk_yes", "bk_no"):
                lines.append(f"def med_{pid}_{kind}_{i} : Prop :=\n  {asg[kind]}\n")
    lines += ["end Claims", ""]

    def names(pid, c, kind):
        return ", ".join(f"``Claims.med_{pid}_{kind}_{i}" for i in range(len(c["assignments"])))

    for reg, prefix in (("registry", ""), ("registryBk", "bk_")):
        lines.append("/-- `(MED pairID, gold is entailment, yes-claims, no-claims)`. -/")
        lines.append(f"def {reg} : List (Nat × Bool × List Lean.Name × List Lean.Name) := [")
        lines.append(",\n".join(
            f"  ({pid}, {'true' if gold == 'entailment' else 'false'}, [{names(pid, c, prefix + 'yes')}], [{names(pid, c, prefix + 'no')}])"
            for pid, gold, c in emitted))
        lines += ["]", ""]
    lines += ["end FraCaS.HeldOut", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
