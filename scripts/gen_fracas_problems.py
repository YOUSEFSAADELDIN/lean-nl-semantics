#!/usr/bin/env python3
"""Generate LeanNLSemantics/FraCaS/Data/Problems.lean from fracas.xml.

Not run automatically as part of the build - the vendored XML doesn't
change, so the generated .lean file is committed like any other source
file. Re-run this script (and re-commit the output) only if
FraCaS/Data/fracas.xml is ever replaced.

Usage: python3 scripts/gen_fracas_problems.py
"""
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XML_PATH = ROOT / "LeanNLSemantics/FraCaS/Data/fracas.xml"
OUT_PATH = ROOT / "LeanNLSemantics/FraCaS/Data/Problems.lean"

ANSWER_MAP = {"yes": ".yes", "no": ".no", "unknown": ".unknown", "undef": ".undef"}


def clean(text: str | None) -> str:
    """Collapse the XML's pretty-printing whitespace into a single sentence."""
    if text is None:
        return ""
    return " ".join(text.split())


def lean_string(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main() -> None:
    tree = ET.parse(XML_PATH)
    problems = tree.getroot().findall("problem")

    entries = []
    skipped = []
    for p in problems:
        pid = int(p.get("id"))
        h_elem = p.find("h")
        hypothesis = clean(h_elem.text if h_elem is not None else None)
        if not hypothesis:
            skipped.append(pid)
            continue
        premises = [clean(pe.text) for pe in p.findall("p")]
        answer = ANSWER_MAP[p.get("fracas_answer")]
        premises_lean = ", ".join(lean_string(s) for s in premises)
        entries.append(
            f"  {{ id := {pid}, premises := [{premises_lean}],\n"
            f"    hypothesis := {lean_string(hypothesis)}, answer := {answer} }}"
        )

    assert len(entries) == 346 - 4, f"expected 342 problems, got {len(entries)}"
    assert skipped == [276, 305, 309, 310], f"unexpected skip list: {skipped}"

    header = f"""/-!
# FraCaS problems (generated)

Generated by `scripts/gen_fracas_problems.py` from
`FraCaS/Data/fracas.xml` — do not hand-edit; re-run the script instead.
{len(entries)} of 346 problems (all but {skipped}, which have an empty
question/hypothesis in the source; see `FraCaS/Types.lean`).

These are data records transcribing the English text, not yet formalized
MTT statements — turning `hypothesis`/`premises` strings into actual CN/
quantifier terms and proving or refuting each one is the real Phase 2
work (see the README roadmap), not this file.
-/
import LeanNLSemantics.FraCaS.Types

namespace FraCaS

def problems : List Problem := [
"""
    footer = (
        f"\n]\n\n"
        f"/-- Regression check that the generator's output made it through\n"
        f"intact: exactly {len(entries)} problems, matching this file's own header. -/\n"
        f"example : problems.length = {len(entries)} := by decide\n\n"
        f"end FraCaS\n"
    )

    OUT_PATH.write_text(header + ",\n".join(entries) + footer)
    print(f"wrote {len(entries)} problems to {OUT_PATH}")


if __name__ == "__main__":
    main()
